const known: ReadonlySet<string> = new Set(COUNTRY_CODES)

/** True for a stored value that is one of the codes; older accounts may still hold a free-text country. */
export function isCountryCode(value: string | null | undefined): value is string {
  return !!value && known.has(value.toUpperCase())
}

const displayNames = new Map<string, Intl.DisplayNames | null>()

/** The country's name in `language` ("IT" → "Italia" / "Italy" / "Italie"), or the code if unknown. */
export function countryName(code: string, language: string): string {
  if (!displayNames.has(language)) {
    try {
      displayNames.set(language, new Intl.DisplayNames([language], { type: 'region' }))
    } catch {
      displayNames.set(language, null)
    }
  }

  return displayNames.get(language)?.of(code.toUpperCase()) ?? code.toUpperCase()
}

/**
 * Flag image from flagcdn.com (free, no key). An image rather than the emoji flag, because Windows renders
 * flag emoji as two letters.
 */
export function flagUrl(code: string): string {
  return `https://flagcdn.com/${code.toLowerCase()}.svg`
}
